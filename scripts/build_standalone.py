#!/usr/bin/env python3
"""Build the dependency-free single-file runner from maintained package sources.

Only regular Python source files below src/am_i_nerfed are included. ZIP_STORED,
fixed metadata, and sorted paths make the generated bytes reproducible across
Python/zlib versions. No build backend, installation, or network is required.
"""

import argparse
import ast
import base64
import hashlib
import io
import os
from pathlib import Path
import re
import sys
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "src" / "am_i_nerfed"
OUTPUT = ROOT / "am-i-nerfed.py"
_MODULE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")


def package_sources(package=PACKAGE):
    """Allowlist Python modules; never copy caches, logs, credentials, or links."""
    package = Path(package)
    if package.is_symlink() or not package.is_dir():
        raise ValueError("Expected a regular src/am_i_nerfed package directory")
    files = []
    for path in package.rglob("*"):
        relative = path.relative_to(package)
        if "__pycache__" in relative.parts or any(part.startswith(".") for part in relative.parts):
            continue
        if path.is_symlink():
            raise ValueError("Source symlinks are not allowed in the standalone bundle")
        if not path.is_file() or path.suffix != ".py":
            continue
        if any(not _MODULE.fullmatch(part) for part in relative.parts[:-1]) or not _MODULE.fullmatch(path.stem):
            raise ValueError("Invalid Python module path in standalone source tree")
        files.append(("am_i_nerfed/" + relative.as_posix(), path.read_bytes()))
    required = {"am_i_nerfed/__init__.py", "am_i_nerfed/__main__.py", "am_i_nerfed/cli.py"}
    if not required.issubset(name for name, _ in files):
        raise ValueError("Standalone source tree is missing package entry points")
    return sorted(files)


def package_version(files):
    source = dict(files)["am_i_nerfed/__init__.py"]
    tree = ast.parse(source, filename="am_i_nerfed/__init__.py")
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(target, ast.Name) and target.id == "__version__"
                                                for target in node.targets):
            value = ast.literal_eval(node.value)
            if isinstance(value, str) and re.fullmatch(r"[0-9][A-Za-z0-9.+-]*", value):
                return value
    raise ValueError("Package must declare a literal __version__ string")


def archive_bytes(files):
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_STORED, allowZip64=False) as archive:
        for name, data in sorted(files):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_STORED
            info.create_system = 3
            info.create_version = 20
            info.extract_version = 20
            info.external_attr = 0o100644 << 16
            info.internal_attr = 0
            info.extra = b""
            info.comment = b""
            archive.writestr(info, data)
    return output.getvalue()


