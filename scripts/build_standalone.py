def build(package=PACKAGE):
    files = package_sources(package)
    payload = archive_bytes(files)
    encoded = base64.b85encode(payload).decode("ascii")
    lines = "\n".join("    b\"" + encoded[start:start + 100] + "\"" for start in range(0, len(encoded), 100))
    metadata = ("_VERSION = " + repr(package_version(files)) + "\n"
                "_PAYLOAD_SHA256 = " + repr(hashlib.sha256(payload).hexdigest()) + "\n"
                "_PAYLOAD_B85 = (\n" + lines + "\n)\n")
    license_text = (ROOT / "LICENSE").read_text(encoding="utf-8").strip()
    license_comments = "\n".join("# " + line if line else "#" for line in license_text.splitlines())
    prefix = _PREFIX.replace('"""Am I Nerfed?', license_comments + '\n\n"""Am I Nerfed?', 1)
    return (prefix + metadata + _SUFFIX).encode("utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Exit nonzero if am-i-nerfed.py is missing or stale")
    args = parser.parse_args(argv)
    try:
        generated = build()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_bytes() != generated:
                print("am-i-nerfed.py is missing or stale; run python3 scripts/build_standalone.py", file=sys.stderr)
                return 1
            print("am-i-nerfed.py is current.")
            return 0
        fd, temporary = tempfile.mkstemp(prefix=".am-i-nerfed-build-", dir=str(OUTPUT.parent))
        try:
            with os.fdopen(fd, "wb") as stream:
                stream.write(generated)
            os.chmod(temporary, 0o644)
            os.replace(temporary, OUTPUT)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
        print("Built am-i-nerfed.py (%d bytes)." % len(generated))
        return 0
    except (OSError, ValueError, SyntaxError) as exc:
        print("Cannot build standalone runner: " + str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
